"""
verify_all_test_topologies.py
-----------------------------
Comprehensive post-molecular physical verification engine for ALL test dataset molecules.

Executes physical and numerical verification across all 122 held-out test molecules
(780 covalent bonds, 458 bond angles):
1. Runs SOTA Hybrid Model (CGSpringHybridModel) inference on every test graph.
2. Generates individual GROMACS .itp topology files for all 122 test molecules.
3. Computes:
   - Vibrational frequency omega = sqrt(k_bond / mu) [ps^-1]
   - Maximum stable Verlet integration time step dt_max = 2000 / omega [fs]
   - 20 fs and 10 fs MD integration stability verification
   - Equipartition thermal fluctuation width sigma_r = sqrt(k_B T / k_bond) [Angstrom]
   - Equipartition angular thermal fluctuation width sigma_theta = sqrt(k_B T / k_angle) [deg]
   - Physical validity bounds (r0 in [0.2, 0.7] nm, theta0 in [40, 180] deg)
   - Discrepancy against ground truth (MAE, relative error %, regime classification)
4. Outputs:
   - results/test_verifications/test_dataset_verification_results.json
   - results/test_verifications/test_dataset_verification_summary.csv
   - results/test_verifications/test_dataset_verification_report.md
   - results/test_verifications/test_dataset_verification_distributions.png
   - Copies summary report and plots to artifact directory.
"""

